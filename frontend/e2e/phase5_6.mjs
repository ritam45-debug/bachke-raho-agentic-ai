// Phase 5 & 6 browser test on the preview build: compliance register, consented feedback, memory, and the
// approval workflow across two users (no self-approval, notifications, outcome).
import { chromium } from 'playwright'
import { resolve } from 'node:path'

const BASE = process.env.SITE_URL ?? 'file://' + resolve('dist-preview/index.html')
const PW = 'Phase56!Test2026'
const ok = (c, m) => { if (!c) { throw new Error(m) } console.log('ok -', m) }
const browser = await chromium.launch(process.env.CHROME_PATH ? { executablePath: process.env.CHROME_PATH, args: ['--no-sandbox'] } : {})
const page = await browser.newPage({ viewport: { width: 1500, height: 1000 } })
const errors = []; page.on('pageerror', (e) => errors.push(String(e)))
const go = (label) => page.click(`nav >> text=${label}`)
const main = () => page.locator('main').innerText()
try {
  await page.goto(BASE)
  await page.getByText('Register your company').first().click()
  await page.locator('input').first().fill('Phase Five Foods')
  await page.fill("input[placeholder='e.g. Electronics manufacturing']", 'Food processing')
  await page.locator("label:has-text('Headquarters') + input").fill('Chennai')
  await page.getByText('Continue').click(); await page.getByText('Continue').click()
  await page.locator("label:has-text('Full name') + input").fill('Asha Admin')
  await page.locator("label:has-text('Work email') + input").fill('admin@p5.example')
  await page.locator('input[type=password]').nth(0).fill(PW); await page.locator('input[type=password]').nth(1).fill(PW)
  await page.check('input[type=checkbox]')
  await page.getByText('Create workspace').click()
  await page.waitForSelector('text=Get set up')
  ok(!(await page.locator('nav').innerText()).match(/P[45]/), 'no phase badges left in navigation')

  // ---- compliance ----
  await go('Legal & Compliance')
  await page.click("button:has-text('Add requirement')")
  const lf = (l) => page.locator(`label:has-text('${l}') + input`).first()
  await lf('Requirement').fill('FSSAI labelling of packaged food'); await lf('Jurisdiction').fill('India'); await lf('Category').fill('Labelling')
  await lf('Regulator').fill('FSSAI'); await lf('Official source URL').fill('notaurl')
  await page.click("button:has-text('Save')")
  await page.waitForSelector('text=/valid URL/')
  ok(true, 'invalid source URL rejected')
  await lf('Official source URL').fill('https://www.fssai.gov.in/')
  const soon = new Date(Date.now() + 20 * 864e5).toISOString().slice(0, 10)
  await lf('Effective date').fill(soon)
  await page.locator("label:has-text('What the source says') + textarea").fill('Labels must show allergen information.')
  await page.click("button:has-text('Save')")
  await page.waitForSelector('text=FSSAI labelling of packaged food')
  let t = await main()
  ok(t.includes('Not yet assessed') && t.includes('No owner') && t.includes('Takes effect within 90 days'), 'attention flags: not assessed, no owner, effective soon')
  ok(/source says \(fact\)/i.test(t) && t.includes('not legal advice'), 'fact shown separately; not-legal-advice notice visible')

  // ---- consumer feedback ----
  await go('Consumer Intelligence')
  await page.click("button:has-text('New survey')")
  await page.locator("label:has-text('Survey title') + input").fill('Q4 delivery experience')
  await page.click("button:has-text('Create')")
  await page.waitForSelector('text=Record a response')
  ok(await page.locator("button:has-text('Save response')").isDisabled(), 'cannot save a response without consent')
  await page.fill("textarea[placeholder^='score,comment']", 'score,comment,region,consent\n10,Arrived on time and fresh,North,yes\n2,Very late and the box was damaged,South,no\n')
  await page.click("button:has-text('Import')")
  await page.waitForSelector('text=/consent is not true/')
  ok(true, 'CSV with a non-consented row is rejected whole')
  await page.fill("textarea[placeholder^='score,comment']", 'score,comment,region,consent\n10,Arrived on time and fresh,North,yes\n2,Very late and the box was damaged,South,yes\n4,Late again,South,yes\n8,ok,North,yes\n')
  await page.click("button:has-text('Import')")
  await page.waitForSelector('text=Responses imported.')
  t = await main()
  ok(/NPS\s*-25/.test(t), 'NPS = (1 promoter − 2 detractors) / 4 = −25')
  ok(t.includes('Late / slow delivery') && t.includes('Damage / packaging'), 'complaint themes detected')
  ok(t.includes('Fewer than 30 responses'), 'small-sample warning shown')

  // ---- memory ----
  await go('Organisational Memory')
  await page.click("button:has-text('Add entry')")
  await page.locator("label:has-text('Title') + input").fill('Chennai port congestion Dec 2025')
  await page.selectOption("label:has-text('Type') + select", 'incident')
  await page.locator("label:has-text('What happened') + textarea").fill('Vessel waits rose to 6 days. Shifting 30% of boxes to Kattupalli cut delays.')
  await page.locator("label:has-text('Tags') + input").fill('Port, chennai')
  await page.click("button:has-text('Save')")
  await page.waitForSelector('article:has-text("Kattupalli")')
  await page.fill("input[placeholder^='Search titles']", 'kattupalli delays'); await page.click("button[type=submit]:has-text('Search')")
  await page.waitForTimeout(300)
  ok(await page.locator('article').count() === 1, 'memory search finds the entry')
  await page.fill("input[placeholder^='Search titles']", 'resin'); await page.click("button[type=submit]:has-text('Search')")
  await page.waitForSelector('text=No entries match.')
  ok(true, 'non-matching search returns nothing')

  // ---- approvals: admin adds an SCM; SCM requests; SCM cannot self-approve; admin approves ----
  await go('Company Settings')
  await page.fill("input[placeholder='Full name']", 'Sam Supply'); await page.fill("input[placeholder='Email']", 'scm@p5.example')
  await page.selectOption("form:has(input[placeholder='Temporary password']) select", 'supply_chain_manager'); await page.fill("input[placeholder='Temporary password']", PW)
  await page.click("form:has(input[placeholder='Temporary password']) button")
  await page.waitForSelector('text=scm@p5.example')
  const signIn = async (email) => {
    await page.click("button[title='Sign out']")
    await page.getByText('Company login').first().click()
    await page.fill('#email', email); await page.fill('#pw', PW); await page.click("button:has-text('Sign in')")
    await page.waitForSelector('nav >> text=Approvals')
  }
  await signIn('scm@p5.example')
  await go('Approvals')
  await page.click("button:has-text('New approval request')")
  const box = page.locator('div.rounded-lg:has-text("New approval request")').last()
  await box.locator('input').first().fill('Air-freight PO-1001 to avoid line stop')
  await box.locator('select').selectOption('expedite_shipment')
  await box.locator("input[type=number]").fill('180000')
  await box.locator('textarea').first().fill('Move 2 t of resin from sea to air.')
  await page.click("button:has-text('Send for approval')")
  await page.waitForSelector('text=Approval requested')
  await go('Approvals')
  await page.waitForSelector('text=Waiting for another approver.')
  ok(await page.locator("button:has-text('Approve')").count() === 0, 'requester sees no Approve button (no self-approval)')

  await signIn('admin@p5.example')
  const bell = page.locator("button[aria-label^='Notifications']")
  await page.waitForFunction(() => /\(1 unread\)/.test(document.querySelector("button[aria-label^='Notifications']")?.getAttribute('aria-label') ?? ''))
  ok(true, 'approver has 1 unread notification')
  await bell.click(); await page.click('text=Approval needed: Air-freight PO-1001')
  await page.waitForSelector("button:has-text('Approve')")
  await page.click("button:has-text('Reject')")
  await page.waitForSelector('text=Give a reason when rejecting')
  ok(true, 'reject without a reason is refused')
  await page.fill("input[placeholder^='Decision note']", 'Within the expedite budget')
  await page.click("button:has-text('Approve')")
  await page.click("button:has-text('All requests')")
  await page.waitForSelector('text=Approved by Asha Admin')
  ok(true, 'admin approved the request')

  await signIn('scm@p5.example')
  await page.waitForFunction(() => /\(1 unread\)/.test(document.querySelector("button[aria-label^='Notifications']")?.getAttribute('aria-label') ?? ''))
  ok(true, 'requester notified of the decision')
  await go('Approvals'); await page.click("button:has-text('All requests')")
  await page.fill("input[placeholder^='What happened after']", 'Arrived in 2 days; line kept running.')
  await page.click("button:has-text('Record outcome')")
  await page.waitForSelector('text=Arrived in 2 days')
  ok(true, 'outcome recorded after approval')

  await signIn('admin@p5.example')
  await go('Audit & Activity')
  await page.waitForSelector('text=approval.outcome_recorded')
  t = await main()
  const missing = ['approval.requested', 'approval.approved', 'approval.outcome_recorded', 'feedback.recorded', 'memory.created', 'compliance.created'].filter((a) => !t.includes(a))
  if (missing.length) console.log('missing:', missing, t.slice(0, 1500))
  ok(['approval.requested', 'approval.approved', 'approval.outcome_recorded', 'feedback.recorded', 'memory.created', 'compliance.created'].every((a) => t.includes(a)), 'all actions in the audit log')
  ok(errors.length === 0, `no page errors ${errors.join('; ')}`)
  console.log('\nPhase 5 & 6 e2e: all checks passed')
} catch (e) {
  console.error('FAIL:', e.message); await page.screenshot({ path: '/tmp/p56-fail.png', fullPage: true }); process.exitCode = 1
} finally { await browser.close() }
